/** Each pool's readers as section ids. */
export function poolReaders(pool: string): string[] {
  const text = POOL_READER_TEXT[pool];
  if (text === undefined) return [];
  const ids = text
    .split(/[,;]/)
    .map((p) => p.trim())
    .filter((p) => p)
    .flatMap((p) => READER_PHRASES[p] ?? []);
  return [...new Set(ids)];
}
