// The coverage report as text (shared lens brief §6.2): `docs/coverage.md` and `docs/coverage.json`
// from the numbers in coverage.ts. Pure string building; `npm run coverage` writes the files.

import { buildCoverage, COVERAGE_ADAPTERS, type CoverageReport, type CultureCell, type ModuleCoverage } from "./coverage";
import { LENS_CULTURES, LENS_ERAS, LENS_STYLES, LENS_TARGETS, LENS_TONES, LENS_REGIONS } from "./lens";
import { SECTION_LABELS, type NameForgeSection } from "./sections";

const label = (module: string) => SECTION_LABELS[module as NameForgeSection] ?? module;
const cultureLabel = (key: string) => LENS_CULTURES.find((c) => c.key === key)?.label ?? key;
const styleLabel = (key: string) => LENS_STYLES.find((s) => s.key === key)?.label ?? key;

/** A culture cell: "words/shapes", in bold when below its target; "excluded" or "not offered" where that's the case. */
function cultureCell(cell: CultureCell | undefined): string {
  if (!cell) return "–";
  if (cell.excluded) return "excluded";
  if (cell.notOffered) return "not offered";
  const text = `${cell.words}/${cell.shapes}`;
  return cell.below ? `**${text}**` : text;
}

const table = (head: string[], rows: string[][]) => [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

const liveLensCultures = () => LENS_CULTURES.filter((c) => (c.tier === "core" || c.tier === "second") && c.status === "live");

/** The report in Markdown, British English. */
export function renderCoverageMarkdown(report: CoverageReport = buildCoverage()): string {
  const mods = report.modules;
  const t = LENS_TARGETS;
  const out: string[] = [];
  out.push("# Coverage report", "");
  out.push(
    "Generated by `npm run coverage` from the tables in `src/data/` read through the shared lens (`src/data/lens.json`); do not edit by hand. It counts entries, not weights, and never runs a generator. Targets are fixed numbers in `lens.json`; cells below target are in **bold**.",
    "",
    "A cell reads *words/shapes*. A shared pool counts in every module that reads it, and once in the totals. A culture's own entries count towards the lens culture its key feeds (`anglo-saxon` and `norman-british` towards English; `celtic` towards Welsh, Scottish and Irish, which are planned and never offered). Whole fixed names (`f: fixed`, the `…Fixed:` pools) are words.",
    "",
  );
  if (report.withoutAdapter.length > 0) {
    out.push(`**Not yet reported** (no adapter yet): ${report.withoutAdapter.map(label).join(", ")}.`, "");
  }

  // 1. Module × culture
  out.push("## 1. Module × culture", "", `Targets: core ${t.cultures.core.words} words and ${t.cultures.core.shapes} shapes; second tier ${t.cultures.second.words} and ${t.cultures.second.shapes}; local ${t.cultures.local.words} and ${t.cultures.local.shapes}. Live lens cultures only; planned cultures are declared and not offered.`, "");
  const live = liveLensCultures();
  out.push(
    table(
      ["module", ...live.map((c) => c.label)],
      mods.map((m) => [label(m.module) + (m.noTables ? " (no tables of its own)" : ""), ...live.map((c) => cultureCell(m.cultures[c.key]))]),
    ),
    "",
  );
  const locals = [...new Set(mods.flatMap((m) => Object.keys(m.cultures).filter((k) => LENS_CULTURES.find((c) => c.key === k)?.tier === "local" || !LENS_CULTURES.some((c) => c.key === k))))].sort();
  if (locals.length > 0) {
    out.push("### Local cultures", "", "Cultures only their own module has (§3.1), at the local-tier target.", "");
    out.push(
      table(
        ["module", ...locals],
        mods.filter((m) => locals.some((k) => m.cultures[k])).map((m) => [label(m.module), ...locals.map((k) => cultureCell(m.cultures[k]))]),
      ),
      "",
    );
  }

  // 2. Module × era, module × style
  out.push("## 2. Module × era and module × style", "", `Era-restricted entries per module (target ${t.era} per era the module offers). Land modules read the land band (EM, ST, MO) as one; entries tagged with five or more eras count as open.`, "");
  const eraMark = (m: ModuleCoverage, v: number) => (v < t.era ? `**${v}**` : String(v));
  out.push(table(["module", ...LENS_ERAS.map((e) => e.code)], mods.map((m) => [label(m.module) + (m.land ? " (land)" : ""), ...LENS_ERAS.map((e) => eraMark(m, m.eras[e.code] ?? 0))])), "");
  const styleKeys = LENS_STYLES.filter((s) => s.key !== "realistic").map((s) => s.key);
  out.push(`Style (words/shapes; target ${t.style.words} and ${t.style.shapes}). Realistic is the default and isn't counted.`, "");
  out.push(
    table(
      ["module", ...styleKeys.map(styleLabel)],
      mods.map((m) => [
        label(m.module),
        ...styleKeys.map((k) => {
          const c = m.styles[k] ?? { words: 0, shapes: 0 };
          const text = `${c.words}/${c.shapes}`;
          return c.words < t.style.words || c.shapes < t.style.shapes ? `**${text}**` : text;
        }),
      ]),
    ),
    "",
  );

  // 3. Module × tone
  out.push("## 3. Module × tone", "", `Tagged entries per tone (target ${t.tone} for grand, grim, light and strange; plain is the default).`, "");
  out.push(table(["module", ...LENS_TONES], mods.map((m) => [label(m.module), ...LENS_TONES.map((tone) => { const v = m.tones[tone] ?? 0; return t.toneKeys.includes(tone) && v < t.tone ? `**${v}**` : String(v); })])), "");

  // 4. Module × region
  const withRegions = mods.filter((m) => m.regions);
  out.push("## 4. Module × region", "", `Entries restricted to or multiplied for each British region (target ${t.region}), for the modules that read regions.`, "");
  out.push(table(["module", ...LENS_REGIONS.filter((r) => r.status === "live").map((r) => r.code)], withRegions.map((m) => [label(m.module), ...LENS_REGIONS.filter((r) => r.status === "live").map((r) => { const v = m.regions![r.code] ?? 0; return v < t.region ? `**${v}**` : String(v); })])), "");

  // 5. Module × kind
  out.push("## 5. Module × kind", "", `Shapes open to every culture, per kind (target ${t.kindOpenShapes}). A shape that names no kind counts for all of the module's kinds.`, "");
  for (const m of mods) {
    const kinds = Object.entries(m.kinds);
    if (kinds.length === 0) continue;
    out.push(`- **${label(m.module)}**: ${kinds.map(([k, v]) => (v < t.kindOpenShapes ? `**${k} ${v}**` : `${k} ${v}`)).join(", ")}`);
  }
  out.push("");

  // 6. Thin pools
  out.push("## 6. Thin pools", "", `Pools and lists under ${LENS_TARGETS.pool} entries, apart from those exempt in \`lens.json\`.`, "");
  out.push(
    table(
      ["pool or list", "module", "entries"],
      report.thinPools.map((p) => [`\`${p.pool}\``, p.module ? label(p.module) : "shared", String(p.entries)]),
    ),
    "",
  );

  // 7. Roster differences
  out.push("## 7. Roster differences", "", "The live lens cultures each module doesn't offer, and the keys it offers that are only its own.", "");
  for (const m of mods) {
    if (!m.roster) continue;
    const missing = m.roster.notOffered.map(cultureLabel);
    out.push(`- **${label(m.module)}**: ${missing.length > 0 ? `doesn't offer ${missing.join(", ")}` : "offers every live lens culture"}${m.roster.localKeys.length > 0 ? `; local: ${m.roster.localKeys.join(", ")}` : ""}.`);
  }
  // A culture a module leaves out of one kind only (no pilgrim routes for Polynesian and Andean) can't be a whole-module cell.
  const kindExclusions = COVERAGE_ADAPTERS.flatMap((a) => (a.excluded ?? []).filter((x) => x.kind).map((x) => `${label(a.module)} has no ${x.kind} kind for ${x.cultures.map(cultureLabel).join(" or ")}`));
  if (kindExclusions.length > 0) out.push("", `Excluded by kind: ${kindExclusions.join("; ")}.`);
  out.push("");

  // 8. Totals
  out.push("## 8. Totals", "", "Distinct entries across the reported modules; a shared pool counts once.", "");
  out.push(table(["lens culture", "words", "shapes"], LENS_CULTURES.filter((c) => c.tier !== "baseline").map((c) => [c.label + (c.status === "planned" ? " (planned)" : ""), String(report.totals.cultures[c.key]?.words ?? 0), String(report.totals.cultures[c.key]?.shapes ?? 0)])), "");
  out.push(table(["era", "entries"], LENS_ERAS.map((e) => [`${e.code} ${e.label}`, String(report.totals.eras[e.code] ?? 0)])), "");
  out.push(table(["style", "words", "shapes"], styleKeys.map((k) => [styleLabel(k), String(report.totals.styles[k]?.words ?? 0), String(report.totals.styles[k]?.shapes ?? 0)])), "");
  out.push(table(["tone", "entries"], LENS_TONES.map((tone) => [tone, String(report.totals.tones[tone] ?? 0)])), "");
  return out.join("\n");
}

/** The same numbers as JSON, for the ratchet test and for diffing. */
export function renderCoverageJson(report: CoverageReport = buildCoverage()): string {
  return `${JSON.stringify(report, null, 1)}\n`;
}

/** What `npm run coverage` writes. */
export function coverageFiles(): { markdown: string; json: string } {
  const report = buildCoverage();
  return { markdown: renderCoverageMarkdown(report), json: renderCoverageJson(report) };
}
