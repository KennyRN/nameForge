// Place modules split brief §6: the class of a kind (natural, managed or constructed) and the class link
// that narrows an "any kind" draw to one class. Obsidian-free. The class is a view over kinds: a kind keeps
// its key, so stored kinds, presets and history are unchanged, and `all` (no class) draws exactly as before.

import offersData from "../data/lens-offers.json";

export type PlaceClass = "natural" | "managed" | "constructed";
export const PLACE_CLASSES: readonly PlaceClass[] = ["natural", "managed", "constructed"];

export const isPlaceClass = (value: unknown): value is PlaceClass => typeof value === "string" && (PLACE_CLASSES as readonly string[]).includes(value);

/** The words each choice reads as in the sentence: "‹all› ‹features of any kind›". */
export const CLASS_TEXT: Record<"all" | PlaceClass, string> = { all: "all", natural: "natural", managed: "managed", constructed: "constructed" };

export const CLASS_TITLE = "Class: natural features, land that people manage, or things people build. Narrows \"any kind\" to one class";

/** The classes a module offers, from `lens-offers.json` (generated by `npm run offers`); none for a module without classes. */
export const classesOffered = (module: string): PlaceClass[] =>
  ((offersData as unknown as { modules: Record<string, { classes?: string[] }> }).modules[module]?.classes ?? []).filter(isPlaceClass);

/** The class link shows only where a module has kinds in at least two classes (§6). */
export const showsClassLink = (module: string): boolean => classesOffered(module).length >= 2;

export interface ClassSegment {
  field: "kindClass";
  text: string;
  title: string;
  choices: { id: string | undefined; label: string }[];
  current: string | undefined;
}

/** The class link for a module in its present class, or undefined where the module doesn't show one. */
export function classSegment(module: string, current: PlaceClass | undefined): ClassSegment | undefined {
  if (!showsClassLink(module)) return undefined;
  const chosen = current && classesOffered(module).includes(current) ? current : current;
  return {
    field: "kindClass",
    text: CLASS_TEXT[chosen ?? "all"],
    title: CLASS_TITLE,
    choices: [{ id: undefined, label: CLASS_TEXT.all }, ...classesOffered(module).map((c) => ({ id: c as string | undefined, label: CLASS_TEXT[c] }))],
    current: chosen,
  };
}

/** Kinds kept by a class: all of them with no class; a kind with no class counts as outside every class. */
export const kindInClass = (kind: { class?: string }, kindClass: PlaceClass | undefined): boolean => !kindClass || kind.class === kindClass;
