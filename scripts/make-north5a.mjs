const wilds = read("wilds");
const waters = read("waters");

const out = {
  _about: "Northern Europe tables brief, batch 5a (docs/northern-europe-tables-brief.md): generated by scripts/make-north5a.mjs from the content in scripts/north5a/. Do not edit by hand.",
  vocab: { pools: {} },
  wilds: { cultureShapes: [], regionColumns: columns(wilds.regionTags, NORDIC_WILDS), regionTags: {}, regionTagFor: {}, cultureMult: {}, homeland: {} },
  waters: { cultureShapes: [], regionColumns: columns(waters.regionTags, NORDIC_WATERS), regionTags: {}, regionTagFor: {}, cultureMult: {}, homeland: {} },
  routes: { cultureShapes: [], regionColumns: {}, regions: {} },
  deities: { styles: {} },
};

writeFileSync(new URL("../src/data/north5a.json", import.meta.url), `${JSON.stringify(out, null, 1)}\n`);
console.log("wrote src/data/north5a.json");
