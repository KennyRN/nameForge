// Second-tier tables brief, batch 6b: writes src/data/tier6b.json and docs/second-tier-6b.md (the generated sections) from the authored content in scripts/tier6b/.
// Run with `node scripts/make-tier6b.mjs`. The output is generated: edit the content, not the JSON. People tables: `node scripts/make-tier6b-people.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { buildSettlement } from "./tier6b/settlementBuild.mjs";
import { CULTURES, NEW_ERAS } from "./tier6b/settlement.mjs";
import { FILLS } from "./tier6b/fills.mjs";
import { tagList, withDesert } from "./tier6d/biomes.mjs";
import turkic from "./tier6b/north5a/turkic.mjs";
import mongol from "./tier6b/north5a/mongol.mjs";
import arabic from "./tier6b/north5a/arabic.mjs";
import persian from "./tier6b/north5a/persian.mjs";
import egyptian from "./tier6b/north5a/egyptian.mjs";
import ethiopian from "./tier6b/north5a/ethiopian.mjs";
import bantu from "./tier6b/north5a/bantu.mjs";
import westAfrican from "./tier6b/north5a/west-african.mjs";
import * as U from "./tier6b/north5b-content.mjs";
import { CW } from "./tier6b/north5c-words.mjs";
import { CW5D } from "./tier6b/north5d-words.mjs";

const out = { _about: "Second-tier tables brief, batch 6b (docs/second-tier-tables-brief.md): generated by scripts/make-tier6b.mjs from the content in scripts/tier6b/. Do not edit by hand." };
out.settlement = buildSettlement();
/** The 6b cultures' own plant, tree, bird, beast and water-creature fills (src/settlement/vocab.ts reads them in place of the shared lists). */
out.fills = Object.fromEntries(Object.entries(FILLS).map(([c, lists]) => [c, Object.fromEntries(Object.entries(withDesert(c, lists)).map(([k, v]) => [k, tagList(v).split("|")]))]));
writeFileSync(new URL("../src/data/tier6b.json", import.meta.url), `${JSON.stringify(out)}\n`);

const md = [];
md.push("<!-- tier6b-generated:start -->", "", "## Part B: generated entries", "", "Written by `scripts/make-tier6b.mjs` from `scripts/tier6b/`; edit those, not this section. People tables: `docs/people-tables.md`.", "");
md.push("### Settlement names", "");
md.push("A template is a pattern with a weight and the sizes it serves (h hamlet, v village, t town, c city, g great city); `{name}` and `{saint}` are filled from the people tables of the culture, and each list is shown with its words.", "");
for (const c of Object.values(CULTURES)) {
  md.push(`#### ${c.label}`, "", `*${c.guide}*`, "");
  for (const e of c.eras) md.push(`- **${e.label}:** ${e.templates.map(([p, w, s]) => `${p} (${w}, ${s})`).join("; ")}`);
  md.push(`- **Words:** ${Object.entries(c.lists).filter(([k]) => !["adj", "tree", "animal"].includes(k)).map(([k, v]) => `${k}: ${v.replace(/\|/g, ", ")}`).join("; ")}`, "");
}
for (const [id, eras] of Object.entries(NEW_ERAS)) {
  md.push(`#### ${id[0].toUpperCase()}${id.slice(1)} (new era${eras.length > 1 ? "s" : ""}, added before Interstellar)`, "");
  for (const e of eras) md.push(`- **${e.label}:** ${e.templates.map(([p, w, s]) => `${p} (${w}, ${s})`).join("; ")}; words: ${Object.entries(e.lists).map(([k, v]) => `${k}: ${v.replace(/\|/g, ", ")}`).join("; ")}`);
  md.push("");
}
const LS = [turkic, mongol, arabic, persian, egyptian, ethiopian, bantu, westAfrican];
const plain = (t) => t.replace(/\|/g, ", ");
md.push("### Land and sea (lands, farmland, hills, rivers, deserts, the wild lands, seas, coasts, sea charts, route names, sacred places)", "");
md.push("Each noun list is ten words in a fixed order: three of the ancient to medieval eras, three of the early modern to the steam age, two of the steam age to modern, one fantastic (the culture's own lore) and one for every era; Egyptian's own order gives each word its era (one ancient, one ancient to medieval, one medieval, one medieval to early modern, two early modern to steam age, one steam age to modern, one modern, one fantastic, one for every era). The kinds are peak, ridge, range; forest, grove, clearing; moor, hill, stone; marsh, bog, isle; plain, down, vale; country, shire, parish; field, farm, enclosure; hill, valley, ridge; stream, lake, falls; desert, dune, rock; bay, inlet, strait; headland, cove, island; bank, reef, channel; road, trade, pilgrim; water, stone, built (sacred places). The mixes (Turkic and Mongol steppe, Arabic and Persian) hold the first, fourth, ninth and tenth word of the first half's lists. The words of the groups B, C and D are in the generated file `scripts/tier6b/north5a/`.", "");
for (const c of LS) {
  md.push(`#### ${c.label} (${c.style === "first" ? "generic first" : c.style === "last" ? "generic last" : c.style})`, "");
  for (const g of ["land", "water", "route", "sacred"]) md.push(`- **${g} B/C/D:** ${["B", "C", "D"].map((k) => `${k}: ${plain(c[g][k] ?? "")}`).join("; ")}${c[g].N ? `; N: ${plain(c[g].N)}` : ""}`);
  for (const [t, lists] of Object.entries(c.nouns.land)) md.push(`- **${t}:** ${lists.map(plain).join(" / ")}`);
  for (const [t, lists] of Object.entries(c.nouns.water)) md.push(`- **${t}:** ${lists.map(plain).join(" / ")}`);
  md.push(`- **route:** ${c.nouns.route.map(plain).join(" / ")}`, `- **sacred:** ${c.nouns.sacred.map(plain).join(" / ")}`, "");
}
md.push("### Urban (streets and districts, inns and taverns, buildings and landmarks, monuments and statues)", "");
for (const [label, c] of [["Turkic", U.TURKIC], ["Mongol", U.MONGOL], ["Arabic", U.ARABIC], ["Persian", U.PERSIAN], ["Egyptian", U.EGYPTIAN], ["Ethiopian", U.ETHIOPIAN], ["Bantu", U.BANTU], ["West African", U.WEST_AFRICAN]]) {
  md.push(`#### ${label}`, "");
  for (const m of ["streets", "inns", "buildings", "monuments"]) md.push(`- **${m}:** ${c[m].map(plain).join(" / ")}`);
  md.push("");
}
md.push("### Groups, tribes, bynames, realms, peoples and tongues, ships, aircraft and land vehicles", "");
md.push("Three lists of ten words per module and culture, in the module's kind order (`;` between lists; the lists are turned by a step of their own for each culture of a sibling group, so that two siblings never draw the same position of the same list). A word marked @ carries an era span, and * is a fantastic word.", "");
for (const [c, mods] of Object.entries(CW)) { md.push(`#### ${c}`, ""); for (const [m, w] of Object.entries(mods)) md.push(`- **${m}:** ${w.split(";").map(plain).join(" / ")}`); md.push(""); }
md.push("### Money, events, calendars, sky lore, arms, treasures, books and deities", "");
for (const [c, mods] of Object.entries(CW5D)) { md.push(`#### ${c}`, ""); for (const [m, w] of Object.entries(mods)) md.push(`- **${m}:** ${w.split(";").map(plain).join(" / ")}`); md.push(""); }
// Shared words per sibling pair: the words two siblings both hold in a module's lists.
md.push("### Words shared by each sibling pair", "");
md.push("The words two siblings both hold in the same module's lists (land and sea nouns, urban, groups and the 5d modules; each word counted once per module).", "");
const wordsOf = (c, key) => {
  const out = {};
  const grab = (mod, t) => { for (const w of String(t).split(/[;|]/)) { const x = w.split("@")[0].split(";")[0].trim(); if (x) (out[mod] ??= new Set()).add(x); } };
  const l = LS.find((e) => e.key === key);
  for (const g of ["land", "water", "route", "sacred"]) for (const k of ["B", "C", "D", "N"]) if (l[g][k]) grab("landSea", l[g][k].replace(/;[A-Z-]+/g, ""));
  for (const t of Object.values(l.nouns.land)) for (const x of t) grab("landSea", x.replace(/;[A-Z-]+/g, ""));
  for (const t of Object.values(l.nouns.water)) for (const x of t) grab("landSea", x.replace(/;[A-Z-]+/g, ""));
  for (const x of [...l.nouns.route, ...l.nouns.sacred]) grab("landSea", x);
  const urban = { turkic: U.TURKIC, mongol: U.MONGOL, arabic: U.ARABIC, persian: U.PERSIAN, egyptian: U.EGYPTIAN, ethiopian: U.ETHIOPIAN, bantu: U.BANTU, "west-african": U.WEST_AFRICAN }[key];
  for (const m of ["streets", "inns", "buildings", "monuments"]) for (const x of urban[m]) grab("urban", x);
  for (const [m, w] of Object.entries(CW[key])) grab("groups:" + m, w);
  for (const [m, w] of Object.entries(CW5D[key])) grab("5d:" + m, w);
  return out;
};
for (const [a, b] of [["turkic", "mongol"], ["arabic", "persian"], ["arabic", "egyptian"], ["persian", "egyptian"], ["ethiopian", "bantu"], ["ethiopian", "west-african"], ["bantu", "west-african"]]) {
  const A = wordsOf(CW[a], a), B = wordsOf(CW[b], b);
  const rows = [];
  for (const m of Object.keys(A)) { const shared = [...A[m]].filter((w) => B[m]?.has(w)); if (shared.length) rows.push(`${m}: ${shared.join(", ")}`); }
  md.push(`#### ${a} and ${b}`, "", rows.length ? rows.map((r) => `- ${r}`).join("\n") : "None.", "");
}
md.push("<!-- tier6b-generated:end -->", "");
const DOC = new URL("../docs/second-tier-6b.md", import.meta.url);
let doc = readFileSync(DOC, "utf8");
const start = doc.indexOf("<!-- tier6b-generated:start -->");
doc = (start >= 0 ? doc.slice(0, start) : doc).trimEnd() + "\n\n";
writeFileSync(DOC, doc + md.join("\n"));
console.log("wrote src/data/tier6b.json");
