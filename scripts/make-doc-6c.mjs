// Generates docs/second-tier-6c.md: the four cultures' entries by module, culture, kind and era, the East Asian shared-word lists, and the notes on the exemptions.
import fs from "node:fs";
import { NOUNS_6C } from "./tier6c/north5a/index.mjs";
import { INDIAN, CHINESE, JAPANESE, KOREAN } from "./tier6c/north5b-content.mjs";
import { CW } from "./tier6c/north5c-words.mjs";
import { CW5D } from "./tier6c/north5d-words.mjs";

const CULTURES = ["indian", "chinese", "japanese", "korean"];
const LABEL = { indian: "Indian", chinese: "Chinese", japanese: "Japanese", korean: "Korean" };
const POS = ["AN-MD", "AN-MD", "AN-MD", "EM-ST", "EM-ST", "EM-ST", "ST-MO", "ST-MO", "fantastic", "every era"];
const ERA = { "AN-MD": "ancient to medieval", "EM-ST": "early modern to steam age", "ST-MO": "steam age to modern", h: "fantastic", "": "every era", MD: "medieval", MO: "modern", AN: "ancient", EM: "early modern", ST: "steam age", IS: "interstellar", "*": "fantastic" };
const all = Object.fromEntries(CULTURES.map((c) => [c, new Set()]));
const clean = (w) => w.replace(/[;@].*$/, "").trim();
/** A list of words, each with its era: a ten-word list takes the fixed order, a word after the tenth carries its own tag. */
function words(culture, text, positional = true) {
  return text.split("|").map((w, i) => {
    const m = w.match(/^(.*?)(?:[;@](.*))?$/);
    const word = m[1].trim();
    all[culture].add(word.toLowerCase());
    const tag = m[2] !== undefined ? m[2] : positional && i < 10 ? POS[i] : "";
    const era = tag === "fantastic" || tag === "every era" ? tag : ERA[tag] ?? tag;
    return `${word} (${era})`;
  }).join(", ");
}
const out = [];
const P = (s = "") => out.push(s);
P("# Batch 6c: Indian, Chinese, Japanese and Korean (second-tier tables brief §13)");
P();
P("Generated by `scripts/make-doc-6c.mjs` from the word files of `scripts/tier6c/`; do not edit by hand. Every list is ten words in the fixed order (three ancient to medieval, three early modern to steam age, two steam age to modern, one fantastic from the culture's own lore, one for every era); a word after the tenth carries its own era.");
P();
P("## Exemptions and judgement calls");
P();
P("- **Deserts (Japanese and Korean):** Japan and Korea have no deserts of their own, so the desert module has no Japanese or Korean content: no noun list, no shapes. The exemption is marked in `lens.json` (`coverageExempt.desertNames`), the coverage report shows both cells as excluded, and `tests/tier6cCoverage.test.ts` holds that. (This is the brief's ruling for 6c; it differs from the 6b judgement, where every culture had a desert.) The Indian (the Thar) and Chinese (the Gobi, the Taklamakan) deserts are written at full depth.");
P("- **Deferred styles:** stars and space, hyperspace charts, spacecraft and river names stay with the styles brief for the four cultures (`deferred.styles` in `lens.json`), as for every earlier culture.");
P("- **Family names, Chinese, Japanese and Korean:** for these family-first cultures the module's own words are the native surnames (the native and mixed settings), and they count towards the module's target: each surname is a word and a form (the surname written first). English mode keeps only the translated subset (the 15 Chinese pairs and the Japanese and Korean surnames that have a plain English sense); no English surname is invented. Japanese has 37 common surnames and Korean 34 (30 or more each), the new Japanese ones with an English sense where it is plain.");
P("- **Family names, Indian (exempt by design):** Indian family names are made from the son-of and daughter-of forms and place forms, so that no caste-marking surname gets in (the caste safeguard). The cell is marked `exempt: by design` (`coverageByDesign` in `lens.json`), not excluded: Indian stays in the family-names menu and makes names as it does.");
P("- **Loanwords:** every loanword was looked up, and the results and the 18 swaps are in `docs/loanwords.md`.");
P();
P("## Land and sea (lands, farmland, hills, rivers, deserts, wild lands, seas, coasts, sea charts, route names, sacred places)");
for (const c of CULTURES) {
  P(); P(`### ${LABEL[c]}`); P();
  const n = NOUNS_6C[c];
  for (const [group, kinds] of [["land", n.land], ["water", n.water]]) for (const [k, lists] of Object.entries(kinds)) lists.forEach((l, i) => P(`- **${k} ${i + 1}:** ${words(c, l, false)}`));
  n.route.forEach((l, i) => P(`- **route ${i + 1}:** ${words(c, l, false)}`));
  n.sacred.forEach((l, i) => P(`- **sacred ${i + 1}:** ${words(c, l, false)}`));
}
P();
P("## Urban (streets and districts, inns and taverns, buildings and landmarks, monuments and statues)");
const URBAN = { indian: INDIAN, chinese: CHINESE, japanese: JAPANESE, korean: KOREAN };
for (const c of CULTURES) {
  P(); P(`### ${LABEL[c]}`); P();
  for (const [kind, lists] of Object.entries(URBAN[c])) if (Array.isArray(lists)) lists.forEach((l, i) => P(`- **${kind} ${i + 1}:** ${words(c, l)}`));
}
P();
P("## Groups, tribes, bynames, realms, peoples, vessels, money, events, calendars, sky, arms, treasures, books and deities");
for (const c of CULTURES) {
  P(); P(`### ${LABEL[c]}`); P();
  for (const src of [CW[c], CW5D[c]]) for (const [module, text] of Object.entries(src ?? {})) {
    if (typeof text !== "string") continue;
    text.split(";").forEach((l, i) => P(`- **${module} ${i + 1}:** ${words(c, l)}`));
  }
}
P();
P("## East Asian shared words");
P();
P("Brief 6d A3 definition: a word is *ordinary* only if it is on this fixed list of plain English words (colours, numbers, directions, sizes, ages and the function words), which are not counted. Every other word two of the three East Asian cultures share is listed, whatever its kind.");
const ORDINARY = new Set(`black white red green blue yellow grey gray brown golden gold silver purple pink orange dark bright pale light
one two three four five six seven eight nine ten eleven twelve thirteen hundred thousand first second third half
north south east west northern southern eastern western upper lower central middle inner outer far near
great little small big large long short high low wide narrow broad deep tall old new young elder eldest ancient
of the and in on at by to from for with a an beyond beside above below under over new old city town village`.split(/\s+/));
for (const [a, b] of [["chinese", "japanese"], ["chinese", "korean"], ["japanese", "korean"]]) {
  const both = [...all[a]].filter((w) => all[b].has(w));
  const shared = both.filter((w) => !ORDINARY.has(w)).sort();
  P(); P(`### ${LABEL[a]} and ${LABEL[b]}: ${shared.length} shared words (${both.length - shared.length} ordinary words not counted)`); P();
  P(shared.join(", ") || "none");
}
fs.writeFileSync(new URL("../docs/second-tier-6c.md", import.meta.url), out.join("\n") + "\n");
console.log("wrote docs/second-tier-6c.md", out.length, "lines");
