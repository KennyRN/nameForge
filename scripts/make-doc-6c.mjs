P("- **Deferred styles:** stars and space, hyperspace charts, spacecraft and river names stay with the styles brief for the four cultures (`deferred.styles` in `lens.json`), as for every earlier culture.");
P("- **Family names, Chinese, Japanese and Korean:** for these family-first cultures the module's own words are the native surnames (the native and mixed settings), and they count towards the module's target: each surname is a word and a form (the surname written first). English mode keeps only the translated subset (the 15 Chinese pairs and the Japanese and Korean surnames that have a plain English sense); no English surname is invented. Japanese has 37 common surnames and Korean 34 (30 or more each), the new Japanese ones with an English sense where it is plain.");
P("- **Family names, Indian (exempt by design):** Indian family names are made from the son-of and daughter-of forms and place forms, so that no caste-marking surname gets in (the caste safeguard). The cell is marked `exempt: by design` (`coverageByDesign` in `lens.json`), not excluded: Indian stays in the family-names menu and makes names as it does.");
P("- **Loanwords:** every loanword was looked up, and the results and the 18 swaps are in `docs/loanwords.md`.");
