// Generates docs/second-tier-6d.md: the five cultures' entries by module, culture, kind and era, and the notes on the exemptions and the judgement calls.
import fs from "node:fs";
import { NOUNS_6D } from "./tier6d/north5a/index.mjs";
import { AZTEC, MAYA, ANDEAN, POLYNESIAN, AMERICAN } from "./tier6d/north5b-content.mjs";
import { CW } from "./tier6d/north5c-words.mjs";
import { CW5D } from "./tier6d/north5d-words.mjs";
import { CULTURES as SETTLEMENT } from "./tier6d/settlement.mjs";

const CULTURES = ["aztec", "maya", "andean", "polynesian", "american"];
const LABEL = { aztec: "Aztec", maya: "Maya", andean: "Andean", polynesian: "Polynesian", american: "American" };
const POS = ["AN-MD", "AN-MD", "AN-MD", "EM-ST", "EM-ST", "EM-ST", "ST-MO", "ST-MO", "fantastic", "every era"];
const ERA = { "AN-MD": "ancient to medieval", "EM-ST": "early modern to steam age", "ST-MO": "steam age to modern", h: "fantastic", "": "every era", MD: "medieval", MO: "modern", AN: "ancient", EM: "early modern", ST: "steam age", IS: "interstellar", "*": "fantastic" };
const clean = (w) => w.replace(/[;@].*$/, "").trim();
function words(culture, text, positional = true) {
  return text.split("|").map((w, i) => {
    const m = w.match(/^(.*?)(?:[;@](.*))?$/);
    const word = m[1].trim();
    const tag = m[2] !== undefined ? m[2] : positional && i < 10 ? POS[i] : "";
    const era = tag === "fantastic" || tag === "every era" ? tag : ERA[tag] ?? tag;
    return `${word} (${era})`;
  }).join(", ");
}
const out = [];
const P = (s = "") => out.push(s);
P("# Batch 6d: Aztec, Maya, Andean, Polynesian and American (second-tier tables brief §13)");
P();
P("Generated by `scripts/make-doc-6d.mjs` from the word files of `scripts/tier6d/`; do not edit by hand. Every list is ten words in the fixed order (three ancient to medieval, three early modern to steam age, two steam age to modern, one fantastic from the culture's own lore, one for every era), with the later words each carrying its own era. Every word is a plain English word or a loanword looked up in a dictionary (`docs/loanwords.md`); no god's name is used for a deity or a place.");
P();
P("## Exemptions and judgement calls");
P();
P("- **Deserts and moors (Polynesian):** the Polynesian islands have no deserts or moors of their own, so those two modules carry no Polynesian content: no noun list, no shapes. The exemption is marked in `lens.json` (`coverageExempt.desertNames` and `moorNames`), the coverage report shows the cells as excluded, and the distinctness test leaves the Polynesian moor cell out (`excludedCells`). Aztec, Maya, Andean and American deserts are written at target (desert words tagged for the desert biome); no other cell of the five is exempt.");
P("- **Deferred styles:** stars and space, hyperspace charts, spacecraft and river names stay with the styles brief for the five cultures (`deferred.styles` in `lens.json`), as for every earlier culture.");
P("- **Sensitive status stands (Polynesian and Andean), exempt: sensitive:** Polynesian and Andean are living Indigenous traditions, and nothing of their sacred life is invented for them (`docs/deities-and-sacred-places-brief.md` §11.4). Every gate stands as it did before 6d: deities and sacred places are not offered, the money, calendar and sky modules are closed to them, they have no pilgrim roads, no {god}, stone, tomb or figure shapes in buildings and monuments (Polynesian has no faith names, Andean only its Sun Temple), no vessel or vehicle roles beyond those they had, no light, grim or fantastic entries, and no terrain-module settlement branch. Their cells in deities, sacred places, calendars, sky lore and money are marked `exempt: sensitive` in the coverage report (the cells stay excluded, not short). Everything else written for them in 6d stays: settlement names, inns, realms, lands, group names, bynames and the rest. Any change to this is a brief of its own, not a batch decision.");
P("- **American in the group modules:** the group families (orders, guilds, tribes, courts and the like) offer a culture only through a tradition, and American has none, as French and Slavic have none. American is therefore not offered there (its cells read \"not offered\", not below target); its words for them are written and wait for a tradition.");
P("- **Calendars:** each culture's months, festivals and moons are its own words, tagged to eras so that no English farming month (lambing, threshing) is drawn for them.");
P("- **Distinctness:** the five join `distinctness.general` (30% against every other culture and General) and the sibling pairs Aztec / Maya, Aztec / Andean and Maya / Andean and American / Norman and British at 25%; the inn limit of 5% covers every pair. Weights, own-list order and pool offsets were used, never the random stream.");
P("- **Loanwords:** every loanword was looked up; the results and the 8 swaps are in `docs/loanwords.md`.");
P("- **Real names:** 348 real places, events, objects, groups, realms and craft were added to `src/data/real-places.json` for these cultures (Alamo, Battle of Little Bighorn, Boston Tea Party, Chichen Itza, Machu Picchu and the like); no generated name is one.");
P();
P("## Land and sea (lands, farmland, hills, rivers, deserts, wild lands, seas, coasts, sea charts, route names, sacred places)");
for (const c of CULTURES) {
  P(); P(`### ${LABEL[c]}`); P();
  const n = NOUNS_6D[c];
  for (const [group, kinds] of [["land", n.land], ["water", n.water]]) for (const [k, lists] of Object.entries(kinds)) lists.forEach((l, i) => P(`- **${k} ${i + 1}:** ${words(c, l, false)}`));
  n.route.forEach((l, i) => P(`- **route ${i + 1}:** ${words(c, l, false)}`));
  n.sacred.forEach((l, i) => P(`- **sacred ${i + 1}:** ${words(c, l, false)}`));
}
P();
P("## Settlement names (every era)");
for (const c of CULTURES) {
  P(); P(`### ${LABEL[c]}`); P();
  const s = SETTLEMENT[c];
  if (!s) { P("Aztec and Maya gain the eras they lacked; their lists are in the land and sea section."); continue; }
  for (const [k, v] of Object.entries(s.lists ?? {})) P(`- **${k}:** ${v.split("|").join(", ")}`);
}
P();
P("## Urban (streets and districts, inns and taverns, buildings and landmarks, monuments and statues)");
const URBAN = { aztec: AZTEC, maya: MAYA, andean: ANDEAN, polynesian: POLYNESIAN, american: AMERICAN };
for (const c of CULTURES) {
  P(); P(`### ${LABEL[c]}`); P();
  for (const [kind, lists] of Object.entries(URBAN[c])) if (Array.isArray(lists)) lists.forEach((l, i) => P(`- **${kind} ${i + 1}:** ${words(c, l)}`));
}
P();
P("## Groups, tribes, bynames, realms, peoples, vessels, money, events, calendars, sky, arms, treasures, books and deities");
for (const c of CULTURES) {
  P(); P(`### ${LABEL[c]}`); P();
  for (const src of [CW[c], CW5D[c]]) for (const [module, text] of Object.entries(src ?? {})) {
    if (typeof text !== "string") continue;
    text.split(";").forEach((l, i) => P(`- **${module} ${i + 1}:** ${words(c, l)}`));
  }
}
fs.writeFileSync(new URL("../docs/second-tier-6d.md", import.meta.url), out.join("\n") + "\n");
console.log("wrote docs/second-tier-6d.md", out.length, "lines");
