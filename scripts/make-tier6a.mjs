// Second-tier tables brief, batch 6a: writes src/data/tier6a.json and docs/second-tier-6a.md (the generated sections) from the authored content in scripts/tier6a/.
// Run with `node scripts/make-tier6a.mjs`. The output is generated: edit the content, not the JSON. People tables: `node scripts/make-tier6a-people.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { buildSettlement } from "./tier6a/settlementBuild.mjs";
import { CULTURES, NEW_ERAS } from "./tier6a/settlement.mjs";
import { CULTURES_6A } from "./tier6a/north5a/index.mjs";
import spanish from "./tier6a/north5a/spanish.mjs";
import portuguese from "./tier6a/north5a/portuguese.mjs";
import french from "./tier6a/north5a/french.mjs";
import italian from "./tier6a/north5a/italian.mjs";
import dutch from "./tier6a/north5a/dutch.mjs";
import roman from "./tier6a/north5a/roman.mjs";
import slavic from "./tier6a/north5a/slavic.mjs";
import greek from "./tier6a/north5a/greek.mjs";
import byzantine from "./tier6a/north5a/byzantine.mjs";
import * as U from "./tier6a/north5b-content.mjs";

const out = { _about: "Second-tier tables brief, batch 6a (docs/second-tier-tables-brief.md): generated by scripts/make-tier6a.mjs from the content in scripts/tier6a/. Do not edit by hand." };
const settlement = buildSettlement();
out.settlement = settlement;
writeFileSync(new URL("../src/data/tier6a.json", import.meta.url), `${JSON.stringify(out)}\n`);

// The review document: the Part A section is hand-written; every generated section sits between its markers.
const md = [];
md.push("<!-- tier6a-generated:start -->", "", "## Part B: generated entries", "", "Written by `scripts/make-tier6a.mjs` from `scripts/tier6a/`; edit those, not this section. People tables: `docs/people-tables.md`.", "");
md.push("### Settlement names", "");
md.push("A template is a pattern with a weight and the sizes it serves (h hamlet, v village, t town, c city, g great city); `{name}` and `{saint}` are filled from the people tables of the culture, and each list is shown with its words.", "");
for (const [id, c] of Object.entries(CULTURES)) {
  md.push(`#### ${c.label}`, "", `*${c.guide}*`, "");
  for (const e of c.eras) md.push(`- **${e.label}:** ${e.templates.map(([p, w, s]) => `${p} (${w}, ${s})`).join("; ")}`);
  md.push(`- **Words:** ${Object.entries(c.lists).filter(([k]) => !["adj", "tree", "animal"].includes(k)).map(([k, v]) => `${k}: ${v.replace(/\|/g, ", ")}`).join("; ")}`, "");
}
for (const [id, eras] of Object.entries(NEW_ERAS)) {
  md.push(`#### ${id[0].toUpperCase()}${id.slice(1)} (new era${eras.length > 1 ? "s" : ""}, added before Interstellar)`, "");
  for (const e of eras) md.push(`- **${e.label}:** ${e.templates.map(([p, w, s]) => `${p} (${w}, ${s})`).join("; ")}; words: ${Object.entries(e.lists).map(([k, v]) => `${k}: ${v.replace(/\|/g, ", ")}`).join("; ")}`);
  md.push("");
}
md.push("### Land and sea (lands, farmland, hills, rivers, the wild lands, seas, coasts, sea charts, route names, sacred places)", "");
md.push("Each noun list is ten words in a fixed order: three of the ancient to medieval eras, three of the early modern to the steam age, two of the steam age to modern, one fantastic (the culture's own lore) and one for every era. The kinds are peak, ridge, range; forest, grove, clearing; moor, hill, stone; marsh, bog, isle; plain, down, vale; country, shire, parish; field, farm, enclosure; hill, valley, ridge; stream, lake, falls; bay, inlet, strait; headland, cove, island; bank, reef, channel; road, trade, pilgrim; water, stone, built (sacred places). `B` is land use, `C` lore and `D` era words, shared by the group. The mixes (Iberian, Greek and Byzantine) hold the first, fourth, ninth and tenth word of the first culture's lists.", "");
for (const c of [spanish, portuguese, french, italian, dutch, roman, slavic, greek, byzantine]) {
  md.push(`#### ${c.label} (${c.style === "first" ? "generic first" : "generic last"})`, "");
  for (const g of ["land", "water", "route", "sacred"]) md.push(`- **${g} B/C/D:** ${["B", "C", "D"].map((k) => `${k}: ${(c[g][k] ?? "").replace(/\|/g, ", ")}`).join("; ")}${c[g].N ? `; N: ${c[g].N.replace(/\|/g, ", ")}` : ""}`);
  for (const [t, lists] of Object.entries(c.nouns.land)) md.push(`- **${t}:** ${lists.map((l) => l.replace(/\|/g, ", ")).join(" / ")}`);
  for (const [t, lists] of Object.entries(c.nouns.water)) md.push(`- **${t}:** ${lists.map((l) => l.replace(/\|/g, ", ")).join(" / ")}`);
  md.push(`- **route:** ${c.nouns.route.map((l) => l.replace(/\|/g, ", ")).join(" / ")}`, `- **sacred:** ${c.nouns.sacred.map((l) => l.replace(/\|/g, ", ")).join(" / ")}`, "");
}
md.push("### Urban (streets and districts, inns and taverns, buildings and landmarks, monuments and statues)", "");
md.push("Three lists of ten words per module, in the same fixed order; the frames are the 5b ones of the culture's naming style (generic first for Spanish, Portuguese, French, Italian, Roman, Greek and Byzantine; generic last for Dutch and Slavic).", "");
for (const [label, c] of [["Spanish", U.SPANISH], ["Portuguese", U.PORTUGUESE], ["French", U.FRENCH], ["Italian", U.ITALIAN], ["Dutch", U.DUTCH], ["Roman", U.ROMAN], ["Slavic", U.SLAVIC], ["Greek", U.GREEK], ["Byzantine", U.BYZANTINE]]) {
  md.push(`#### ${label}`, "");
  for (const m of ["streets", "inns", "buildings", "monuments"]) md.push(`- **${m}:** ${c[m].map((l) => l.replace(/\|/g, ", ")).join(" / ")}`);
  md.push("");
}
md.push("<!-- tier6a-generated:end -->", "");
const DOC = new URL("../docs/second-tier-6a.md", import.meta.url);
let doc = readFileSync(DOC, "utf8");
const start = doc.indexOf("<!-- tier6a-generated:start -->");
if (start >= 0) doc = doc.slice(0, start).trimEnd() + "\n\n";
else doc = doc.trimEnd() + "\n\n";
writeFileSync(DOC, doc + md.join("\n"));
console.log("wrote src/data/tier6a.json", Object.keys(out).length - 1, "sections");
