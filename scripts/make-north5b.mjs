// Northern Europe tables brief, batch 5b: writes src/data/north5b.json and docs/northern-europe-5b.md from the authored content in
// scripts/north5b/. Run with `node scripts/make-north5b.mjs`. The output is generated: edit the content, not the JSON.
import { writeFileSync } from "node:fs";
import { buildSettlement } from "./north5b/settlementBuild.mjs";
import { buildModules, CULTURES, MODULES } from "./north5b/modules.mjs";
import { CULTURES as SETTLEMENT } from "./north5b/settlement.mjs";
import { REGIONS } from "./north5b/regions.mjs";

const settlement = buildSettlement();
const { out: modules, listing } = buildModules();
const out = {
  _about: "Northern Europe tables brief, batch 5b (docs/northern-europe-tables-brief.md): generated by scripts/make-north5b.mjs from the content in scripts/north5b/. Do not edit by hand.",
  settlement,
  nounPools: Object.values(MODULES).flatMap((m) => m.pools),
  vocab: modules.vocab,
  streets: modules.streets,
  inns: { ...modules.inns, tradition: { welsh: [0.5, "MD"], scottish: [0.5, "MD"], irish: [0.5, "MD"], cornish: [0.5, "MD"], scandinavian: [0.4, "EM"], german: [0.4, "MD"] } },
  buildings: modules.buildings,
  monuments: modules.monuments,
};
writeFileSync(new URL("../src/data/north5b.json", import.meta.url), `${JSON.stringify(out)}\n`);

// ── The review document ────────────────────────────────────────────────────
const md = [];
md.push("# Northern Europe tables: batch 5b\n");
md.push("For Kenny's review. Generated by `scripts/make-north5b.mjs` from `scripts/north5b/`: every entry the batch adds to settlement names, streets and districts, inns and taverns, buildings and landmarks, monuments and statues (the settlement kit composes them and has no tables of its own).\n");
md.push("**How to read it.** A word list reads `Word` with its eras after a semicolon. Each list has ten words in a fixed order: three of the ancient to medieval eras (`AN-MD`), three of the early modern to the steam age (`EM-ST`), two of the steam age to modern (`ST-MO`), one fantastic (`h`, the culture's own lore) and one for every era. Celtic holds eight words per list. A frame is a name shape: `{N0}`, `{N1}` and `{N2}` are the module's own nouns of its three main kinds.\n");
md.push("## Settlement names (B1)\n");
md.push("Each culture names settlements in English, as the world engine's cultures do. Templates carry the sizes they serve: h hamlet, v village, t town, c city, g great city. `{name}` and `{saint}` come from the people tables. Region templates are drawn only when a region is chosen.\n");
for (const [id, c] of Object.entries(SETTLEMENT)) {
  md.push(`### ${c.label}\n`);
  md.push(`${c.guide}\n`);
  for (const e of c.eras) md.push(`- **${e.label}:** ${e.templates.map(([p, w, s]) => `\`${p}\` (${w}, ${s})`).join(", ")}`);
  for (const [k, v] of Object.entries(c.lists)) md.push(`- **${k}:** ${v.replace(/\|/g, ", ")}`);
  for (const [r, v] of Object.entries(c.regions ?? {})) md.push(`- **${r}:** ${v.templates.map(([p, w, s]) => `\`${p}\` (${w}, ${s})`).join(", ")}; ${Object.entries(v.lists).map(([k, l]) => `${k}: ${l.replace(/\|/g, ", ")}`).join("; ")}`);
  md.push("");
}
md.push("## The other modules (B2)\n");
for (const c of CULTURES) {
  md.push(`### ${c.label}\n`);
  md.push(`Keys: ${c.keys.join(", ")}. Names with the generic ${c.c.style === "first" ? "first" : "last"}. Adjectives of the plain frames: ${c.c.adj.join(", ")}.\n`);
  for (const [module, m] of Object.entries(MODULES)) {
    md.push(`- **${m.label}:**`);
    m.kinds.forEach((k, i) => md.push(`  - ${k} (\`${m.pools[i]}\`): ${c.c[m.id][i].replace(/\|/g, ", ")}`));
    const x = c.c.x?.[m.id] ?? [];
    if (x.length) md.push(`  - extra frames: ${x.map(([p, w]) => `\`${p}\` (${w})`).join(", ")}`);
  }
  md.push("");
}
md.push("## Region words\n");
md.push("Six per region and module; drawn only for the cultures that read the region. Each module has three region frames (`{R}`, `{town} {R}`, `{person:poss} {R}`), which take 30% of the draws when a region is chosen.\n");
md.push("| Region | Cultures | Streets | Inns | Buildings | Monuments |\n|---|---|---|---|---|---|");
for (const [code, r] of Object.entries(REGIONS)) md.push(`| ${code} | ${r.cultures.join(", ")} | ${r.streets.replace(/\|/g, ", ")} | ${r.inns.replace(/\|/g, ", ")} | ${r.buildings.replace(/\|/g, ", ")} | ${r.monuments.replace(/\|/g, ", ")} |`);
md.push("\n## Loanwords (rule 4)\n");
md.push("Words in this batch that are dictionary loanwords or regional entries: Tolbooth, Howff, Wynd, Vennel, Gait, Brae, Close, Bothy, Kirk, Strath, Glen, Voe, Haaf, Haa, Broch, Dun, Rath, Quoit, Cromlech, Dolmen, Ogham, Boreen, Shebeen, Torg, Tron, Mercat, Peel, Dyke, Polder, Esker, Fjord, Skerry, Ness, Holm, Wick, Thorp, Hythe, Burg, Gasthof, Calvary, Hunebed, Cairn, Combe, Tor, Wheal, Knocker, Tomte, Piskie, Draugr (replaced by Walking Dead in 5a).\n");
writeFileSync(new URL("../docs/northern-europe-5b.md", import.meta.url), `${md.join("\n")}\n`);
await import("./north5b/patchPools.mjs");
console.log("wrote src/data/north5b.json", { cultures: settlement.cultures.length, pools: Object.keys(modules.vocab.pools).length });
